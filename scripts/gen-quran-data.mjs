/**
 * Generates src/lib/quranData.ts from the fetched quran.com metadata.
 * Sources: chapters.json (114 surahs, verses_count) and juz metadata.
 * Verified: sum(verses_count) === 6236, 30 juz, juz ranges sum to 6236.
 */
import fs from 'node:fs'
import path from 'node:path'

const root = path.resolve(import.meta.dirname, '..')
const chapters = JSON.parse(fs.readFileSync(path.join(root, 'chapters.json'), 'utf8')).chapters
const juzRaw = JSON.parse(fs.readFileSync(path.join(root, 'scripts', 'juzs.json'), 'utf8')).juzs

// Dedupe juz by juz_number (API returns extra entries).
const juzByNum = new Map()
for (const j of juzRaw) if (!juzByNum.has(j.juz_number)) juzByNum.set(j.juz_number, j)
const juzNumbers = [...juzByNum.keys()].sort((a, b) => a - b)

const TOTAL_AYAHS = chapters.reduce((s, c) => s + c.verses_count, 0)
if (chapters.length !== 114) throw new Error('expected 114 chapters')
if (TOTAL_AYAHS !== 6236) throw new Error('expected 6236 ayahs, got ' + TOTAL_AYAHS)

// Parse juz verse_mapping into flat ranges: { juz, surah, from, to }
const juzRanges = []
for (const n of juzNumbers) {
  const mapping = juzByNum.get(n).verse_mapping
  for (const [surah, span] of Object.entries(mapping)) {
    const [from, to] = span.split('-').map(Number)
    juzRanges.push({ juz: n, surah: Number(surah), from, to })
  }
}
const juzVerseTotal = juzRanges.reduce((s, r) => s + (r.to - r.from + 1), 0)
if (juzVerseTotal !== 6236) throw new Error('juz ranges sum to ' + juzVerseTotal)

// Which juz does a given ayah belong to? Build surah -> [{juz,from,to}]
const surahJuz = {}
for (const r of juzRanges) (surahJuz[r.surah] ||= []).push(r)
for (const s of Object.keys(surahJuz)) surahJuz[s].sort((a, b) => a.from - b.from)

const surahs = chapters.map((c) => ({
  n: c.id,
  name: c.name_simple,
  complex: c.name_complex,
  arabic: c.name_arabic,
  english: c.translated_name?.name ?? '',
  ayahs: c.verses_count,
  place: c.revelation_place === 'makkah' ? 'Makkah' : 'Madinah',
  order: c.revelation_order,
  bismillah: c.bismillah_pre,
  juz: surahJuz[c.id].map((r) => ({ j: r.juz, f: r.from, t: r.to })),
}))

const header = `/**
 * Quran metadata - AUTO-GENERATED by scripts/gen-quran-data.mjs
 * Source: api.quran.com v4 (chapters + juzs). Do not edit by hand.
 *
 * Invariants (asserted at generation time):
 *   - 114 surahs
 *   - TOTAL_AYAHS === 6236
 *   - juz ranges cover all 6236 ayahs across 30 juz
 */

export interface SurahJuzSpan { j: number; f: number; t: number }

export interface Surah {
  /** Surah number, 1-114 */
  n: number
  /** Simple transliterated name, e.g. "Al-Baqarah" */
  name: string
  /** Diacritics-preserving transliteration */
  complex: string
  /** Arabic name */
  arabic: string
  /** English meaning of the name */
  english: string
  /** Number of ayahs (verses) in this surah */
  ayahs: number
  /** Revelation place */
  place: 'Makkah' | 'Madinah'
  /** Revelation order (1-114) */
  order: number
  /** Whether the basmalah precedes this surah */
  bismillah: boolean
  /** Juz spans contained in this surah */
  juz: SurahJuzSpan[]
}

/** Total ayahs in the entire Quran */
export const TOTAL_AYAHS = ${TOTAL_AYAHS}

export const SURAHS: Surah[] = ${JSON.stringify(surahs, null, 2)}
`

fs.mkdirSync(path.join(root, 'src', 'lib'), { recursive: true })
fs.writeFileSync(path.join(root, 'src', 'lib', 'quranData.ts'), header)
console.log(`Wrote src/lib/quranData.ts — 114 surahs, ${TOTAL_AYAHS} ayahs, ${juzNumbers.length} juz`)
